// Interface icons: writes src/components/world/solar-icons.ts, holding only the SVG bodies and view boxes of the Solar icons the site uses,
// taken from the @iconify-json/solar package in node_modules. Nothing is fetched at run time or at build time: the icons are in the bundle,
// and no request ever goes to api.iconify.design. Run from apps/site: node scripts/icons.mjs (npm script: "icons").
// To use another Solar icon, add it to USED below (name on the left is the site's own, the Solar id on the right), run this, and use it
// from src/components/world/icons.tsx. Re-runs overwrite the generated file.
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getIconData } from '@iconify/utils';

const require = createRequire(import.meta.url);
const set = require('@iconify-json/solar/icons.json');
const out = join(resolve(dirname(fileURLToPath(import.meta.url)), '..'), 'src', 'components', 'world', 'solar-icons.ts');

// Linear (1.5 stroke, the hairline world) for outlines; Bold where a solid glyph sits in a filled circle.
const USED = {
  pin: 'pin-bold', // the pin badge on the headline (white on ink)
  plus: 'add-linear', // also turned 45 degrees to make the close X: Solar has no bare X
  arrowUp: 'arrow-up-bold', // the send arrow
  arrowRight: 'arrow-right-bold', // the send pill's arrow
  menu: 'hamburger-menu-linear',
  page: 'document-text-linear', // "See the page"
  file: 'file-text-linear', // an attachment
  source: 'notes-minimalistic-linear', // the cite chip
  external: 'arrow-right-up-linear',
  chevronRight: 'alt-arrow-right-linear',
  chevronLeft: 'alt-arrow-left-linear',
  chevronDown: 'alt-arrow-down-linear',
  play: 'play-bold',
  receipt: 'check-circle-linear', // "checked by a person"
  check: 'check-linear', // a chosen chip
  alert: 'danger-circle-linear',
  note: 'info-circle-linear',
};

const icons = {};
for (const [name, id] of Object.entries(USED)) {
  const data = getIconData(set, id);
  if (!data) throw new Error(`Solar has no icon "${id}" (for ${name})`);
  icons[name] = { id, body: data.body, width: data.width ?? 24, height: data.height ?? 24 };
}
const q = (s) => JSON.stringify(s); // the bodies hold double quotes; a JSON string needs no further escaping
writeFileSync(
  out,
  `// GENERATED by scripts/icons.mjs (npm run icons) from @iconify-json/solar. Do not edit by hand: change USED in the script and run it again.
// Only the icons the site uses: their SVG bodies and view boxes. Solar is by 480 Design (CC BY 4.0); see the README.

export interface SolarIcon {
  /** The Solar icon this was taken from. */
  id: string;
  body: string;
  width: number;
  height: number;
}

export const solar = {
${Object.entries(icons)
  .map(([n, i]) => `  ${n}: { id: ${q(i.id)}, body: ${q(i.body)}, width: ${i.width}, height: ${i.height} },`)
  .join('\n')}
} as const satisfies Record<string, SolarIcon>;
`,
);
console.log(`wrote ${Object.keys(icons).length} icons to ${out}`);
